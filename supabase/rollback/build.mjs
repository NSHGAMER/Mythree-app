// Builds supabase/rollback/<version>.down.sql from templates/.
// A line "-- @restore <migration file> <function name>" is replaced by that function's definition copied
// verbatim from the migration, so rollbacks always restore exactly what the previous version shipped.
//   node supabase/rollback/build.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const migrations = join(here, '..', 'migrations')

function extract(file, name) {
  const lines = readFileSync(join(migrations, file), 'utf8').split('\n')
  const start = lines.findIndex((l) => l.startsWith(`create or replace function public.${name}(`))
  if (start < 0) throw new Error(`${name} not found in ${file}`)
  const end = lines.findIndex((l, i) => i > start && /^(end )?\$\$;\s*$/.test(l))
  if (end < 0) throw new Error(`end of ${name} not found in ${file}`)
  return `-- restored from ${file}\n` + lines.slice(start, end + 1).join('\n')
}

for (const t of readdirSync(join(here, 'templates')).filter((f) => f.endsWith('.down.sql')).sort()) {
  const src = readFileSync(join(here, 'templates', t), 'utf8')
  const out = src.replace(/^-- @restore (\S+) (\S+)$/gm, (_, file, name) => extract(file, name))
  writeFileSync(join(here, t), `-- GENERATED by supabase/rollback/build.mjs from templates/${t} – edit the template, not this file.\n${out}`)
  console.log('built', t)
}
